"""使用指南对话框：功能总览 + 常用工作流 + 注意事项（新手防挫折）"""

from PyQt6.QtWidgets import (QDialog, QDialogButtonBox, QTabWidget,
                             QTextBrowser, QVBoxLayout, QWidget)

GUIDE_TEXT = """\
════════════════════════════════════════════
 声鉴·曲库管家 · 使用指南
════════════════════════════════════════════

■ 这个软件能做什么
  扫描一个音乐文件夹（含子文件夹），鉴定每首歌是真无损还是假无损，
  并帮你完成去重、规范命名、按歌单整理等曲库管理工作。

────────────────────────────────────────────
■ 功能一览
────────────────────────────────────────────
[扫描区 · 左栏]
  · 选择文件夹 / 拖拽文件夹：设定目标文件夹，递归扫描子文件夹
  · 线程数 / 分析时长：默认 8 线程、每首从头分析 30 秒（与旧脚本口径一致）
  · 质量标记…：自定义判定后加到文件名上的标记文本和位置（前缀/后缀）
  · 安全模式：开启后所有产出都写入「安全输出」目录，原文件零改动（见下文）

[结果表 · 双击与右键]
  · 双击任意行：查看该文件完整详情（可打开所在文件夹）
  · 右键（可多选）：打开所在文件夹 / 复制完整路径

[结果表 · 工具栏]
  · 筛选：全部 / 只看真无损 / 只看假无损；点表头可排序
  · 导出CSV：全部 / 仅选中行 / 仅假无损 / 仅真无损；UTF-8-BOM，Excel 直接打开
  · 一键重命名：按判定给文件名加质量标记（如 歌名_假无损.flac）
  · 同名对比：把重复文件并排对比各项指标（只看不改）
  · 去重清除：重复组保留一个（默认评分最高，可在对比表点"处置"行改），
    其余移入 目标文件夹/_待清除/（可恢复，见"还原清除"）
  · 还原清除：把 _待清除/ 里的文件移回原来的位置
  · 标签改名：按文件内的歌名/歌手标签统一命名为 歌名-歌手（或反过来）
  · 歌单导入：把歌单（粘贴文本 / md、csv、txt 文件 / 网易云链接）
    匹配到的歌复制到 以歌单名命名的新文件夹，未匹配的歌会写 未匹配清单.txt
    并自动复制到剪贴板

────────────────────────────────────────────
■ 常用工作流
────────────────────────────────────────────
工作流 1 · 鉴定并标记曲库
  选文件夹 → 开始扫描 → 一键重命名（加质量标记）→ 导出CSV 留档

工作流 2 · 精简曲库（去重）
  扫描 → 同名对比（确认差异）→ 去重清除（确认保留项）→
  检查 _待清除/ 无误后手动删除该目录；后悔了用 还原清除

工作流 3 · 规范命名 + 按歌单整理
  扫描 → 标签改名（统一 歌名-歌手）→ 一键重命名（加标记）→
  歌单导入（粘贴歌单文本或网易云链接）→ 歌以副本形式进歌单文件夹
  ※ 加了 _真无损/_假无损 标记的歌也能正常匹配歌单（匹配前会自动剥标记）
  ※ 导出 CSV 的前两列就是"歌名,歌手"，可直接粘贴进歌单导入框

────────────────────────────────────────────
■ 注意事项（重要，请读一遍）
────────────────────────────────────────────
1. 会改文件名的操作（一键重命名/标签改名）执行前都有预览列表，
   确认无误再点执行；单条失败不中断整批，失败原因看日志红字。
2. 去重清除只移动不删除：被清除的进 _待清除/，确认后自己删；
   删除动作软件永远不会替你做。
3. 判定是启发式：频谱分析能识别"有损转无损"等常见造假，
   但不能 100% 保证；重要文件建议先对比试听再清理。
4. 去重靠"标签/文件名 + 内容签名"两路识别；不同音质、无标签、
   文件名也不同的重复（例如重新抓轨的两个版本）识别不了。
5. 歌单导入是复制不是移动，原件不动；歌单文件夹在目标文件夹内，
   再次扫描会被扫到（可用去重清理或把它移出曲库）。
6. 网易云链接：公开歌单可直接解析全量；私密歌单（仅自己可见）
   拿不到，请改用 App 内复制歌单文本手动粘贴。
7. 扫描会跳过 _待清除/ 目录；无权限的子目录跳过并在日志计数。

────────────────────────────────────────────
■ 安全模式（强烈建议新手先开）
────────────────────────────────────────────
  左栏勾选"安全模式"后：
  · 扫描、分析照旧（本来就是只读，绝不改原文件）
  · 一键重命名 / 标签改名：把原文件【复制】到安全输出目录再改名，
    原文件零改动
  · 去重清除：只从结果列表移除被清除项（索引层面），不碰任何文件
  · 歌单导入：歌单文件夹建在安全输出目录里
  · 安全输出目录 = 目标文件夹同级的"<文件夹名>_安全输出/"
  建议：新手先开安全模式跑一遍全流程，确认产出符合预期，
  再关掉安全模式对真实曲库操作。
════════════════════════════════════════════
"""

